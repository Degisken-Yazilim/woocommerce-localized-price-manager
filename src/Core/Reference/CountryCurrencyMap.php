	/**
	 * Get the symbol the reference map records for a currency.
	 *
	 * @param string $currency_code ISO 4217 currency code.
	 * @return string|null Symbol, or null when no country of the map uses the currency.
	 */
	public static function get_currency_symbol( string $currency_code ): ?string {
		$currency = strtoupper( trim( $currency_code ) );

		foreach ( self::get_map() as $entry ) {
			if ( $entry[0] === $currency ) {
				return $entry[1];
			}
		}

		return null;
	}

	/**
	 * Get the decimal count of a currency, as the reference map records it.
	 *
	 * @param string $currency_code ISO 4217 currency code.
	 * @return int|null Decimal count, or null when no country uses the currency.
	 */
	public static function get_currency_decimals( string $currency_code ): ?int {
		$currency = strtoupper( trim( $currency_code ) );

		foreach ( self::get_map() as $entry ) {
			if ( $entry[0] === $currency ) {
				return $entry[4];
			}
		}

		return null;
	}
